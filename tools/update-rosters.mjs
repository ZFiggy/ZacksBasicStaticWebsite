// Public ESPN roster + depth-chart snapshot. No credentials or frontend network calls.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const context = {window: {}};
vm.runInNewContext(await readFile(new URL('public/scripts/teams-data.js', root), 'utf8'), context);
const teams = context.window.NFL_TEAMS;
const overrides = JSON.parse(await readFile(new URL('tools/roster-role-overrides.json', root), 'utf8'));
const endpoint = 'https://site.api.espn.com/apis/site/v2/sports/football/nfl/teams/';
const aliases = {WAS: 'wsh', LA: 'lar', JAC: 'jax'};
const positions = {
    quarterback: ['QB'], runner: ['RB', 'FB'], receiver: ['WR', 'TE'],
    lineman: ['OT', 'T', 'OG', 'G', 'C', 'OL'], corner: ['CB', 'DB'],
    safety: ['S', 'FS', 'SS'], rusher: ['DE', 'DT', 'NT', 'LB', 'OLB', 'ILB', 'EDGE'],
    kicker: ['PK', 'K'], holder: ['P'], snapper: ['LS']
};
export function castFor(roster, depth) {
    const active = roster.athletes.filter(g => ['offense', 'defense', 'specialTeam'].includes(g.position)).flatMap(g => g.items).filter(p => /^\d{1,2}$/.test(p.jersey || ''));
    const byId = new Map(active.map(p => [p.id, p]));
    const slots = depth.depthchart.flatMap(g => Object.values(g.positions));
    // Starters first, then backups; only players still on the active roster qualify.
    const ranked = [];
    for (let rank = 0; rank < 5; rank++) for (const slot of slots) {
        const p = byId.get(slot.athletes[rank]?.id);
        if (p && !ranked.includes(p)) ranked.push(p);
    }
    active.forEach(p => { if (!ranked.includes(p)) ranked.push(p); });
    const cast = Object.fromEntries(Object.entries(positions).map(([role, allowed]) => [role, ranked.filter(p => allowed.includes(p.position.abbreviation)).map(p => ({
        id: p.id, name: p.displayName, number: Number(p.jersey), position: p.position.abbreviation,
        height: p.height, weight: p.weight
    }))]));
    cast.receiver.sort((a, b) => Number(a.position !== 'WR') - Number(b.position !== 'WR'));
    for (const [role, minimum] of Object.entries({quarterback: 1, runner: 1, receiver: 3, lineman: 2, corner: 3, safety: 2, rusher: 3, kicker: 1, holder: 1, snapper: 1})) {
        assert.ok(cast[role].length >= minimum, `Insufficient active ${role} players; keeping previous snapshot`);
        assert.ok(cast[role].every(p => p.name && Number.isInteger(p.number) && p.number >= 0 && p.number <= 99), `Invalid ${role} identity`);
    }
    return cast;
}
async function get(url) {
    const response = await fetch(url, {signal: AbortSignal.timeout(30000)});
    if (!response.ok) throw new Error(`${response.status}: ${url}`);
    return response.json();
}
if (process.argv.includes('--check')) {
    const data = JSON.parse(await readFile(new URL('public/assets/characters/current-rosters.json', root)));
    assert.equal(Object.keys(data.teams).length, 32);
    for (const team of Object.values(data.teams)) for (const players of Object.values(team.cast)) {
        assert.equal(new Set(players.map(p => p.id)).size, players.length);
    }
    const js = await readFile(new URL('public/scripts/current-rosters.js', root), 'utf8');
    assert.equal(js, '// Generated by node tools/update-rosters.mjs\nwindow.currentRosters = ' + JSON.stringify(data) + ';\n');
    console.log('PASS 32 current roster snapshots and browser data agree.');
} else {
    const month = new Date().getUTCMonth();
    if (process.argv.includes('--in-season') && month >= 2 && month <= 6) {
        console.log('March–July: weekly in-season update skipped.');
    } else {
        const results = {};
        // Bounded concurrency; validate every team before replacing either output.
        for (let start = 0; start < teams.length; start += 4) await Promise.all(teams.slice(start, start + 4).map(async team => {
            const code = aliases[team.short] || team.short.toLowerCase();
            const source = endpoint + code + '/roster';
            const depthSource = endpoint + code + '/depthcharts';
            const [roster, depth] = await Promise.all([get(source), get(depthSource)]);
            const cast = castFor(roster, depth);
            const reviewed = overrides[team.id];
            for (const [role, ids] of Object.entries(reviewed?.roles || {})) {
                const preferred = ids.map(id => cast[role].find(p => p.id === id)).filter(Boolean);
                cast[role] = [...preferred, ...cast[role].filter(p => !ids.includes(p.id))];
            }
            results[team.id] = {source, depthSource, reviewedRoleSource: reviewed?.source, season: roster.season?.year, cast};
            console.log(`${team.short}: active roster and depth chart validated`);
        }));
        const assigned = new Map();
        for (const [teamId, team] of Object.entries(results)) for (const player of Object.values(team.cast).flat()) {
            assert.ok(!assigned.has(player.id) || assigned.get(player.id) === teamId, `Player ${player.name} appears on two teams; retry when the feed settles`);
            assigned.set(player.id, teamId);
        }
        const data = {updatedAt: new Date().toISOString(), note: 'Active roster membership; depth chart order where available, roster order otherwise. Punter used as holder unless a reviewed team override exists. Not a game-day inactive report.', teams: Object.fromEntries(teams.map(t => [t.id, results[t.id]]))};
        await mkdir(new URL('public/assets/characters/', root), {recursive: true});
        await writeFile(new URL('public/assets/characters/current-rosters.json', root), JSON.stringify(data, null, 4) + '\n');
        await writeFile(new URL('public/scripts/current-rosters.js', root), '// Generated by node tools/update-rosters.mjs\nwindow.currentRosters = ' + JSON.stringify(data) + ';\n');
        console.log('Updated all 32 teams. No deployment performed.');
    }
}
