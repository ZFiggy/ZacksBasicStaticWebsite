"""Validate original generated atlases and record source rectangles; never repaint faces."""
from PIL import Image
from pathlib import Path
import json, statistics, sys
import cv2
import numpy as np
root=Path(__file__).resolve().parents[2]
queue=json.loads((root/'tools/player-likenesses/queue.json').read_text())
players={}
partial='--partial' in sys.argv
for sheet in queue['sheets']:
    src=f"assets/characters/likenesses/heads-{sheet['index']:02}.png"
    path=root/'public'/src
    if not path.exists():
        if partial: continue
        raise ValueError(f'Missing {path}')
    image=Image.open(path).convert('RGBA')
    assert image.width==image.height, f'{src}: square grid required'
    cell=image.width/6
    for i, p in enumerate(sheet['players']):
        left,top=round(i%6*cell),round(i//6*cell)
        right,bottom=round((i%6+1)*cell),round((i//6+1)*cell)
        tile=image.crop((left,top,right,bottom))
        alpha=tile.getchannel('A')
        solid=alpha.point(lambda a:255 if a>160 else 0)
        labels_count, labels, stats, _ = cv2.connectedComponentsWithStats(np.asarray(solid), 8)
        largest = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
        bx,by,bw,bh,area = (int(v) for v in stats[largest])
        bounds=(bx,by,bx+bw,by+bh)
        assert bounds, f'{p["name"]}: empty cell'
        x0,y0,x1,y1=bounds
        assert (x1-x0)*(y1-y0)>cell*cell*.22, f'{p["name"]}: undersized head'
        clear=sum(1 for v in np.asarray(alpha).flat if v<10)
        assert clear>cell*cell*.12, f'{p["name"]}: no transparent margin'
        # Color sampling from lower cheek/chin keeps bare arms matched to the artwork.
        samples=[]
        for y in range(round(y0+(y1-y0)*.40),round(y0+(y1-y0)*.61)):
            for x in range(round(x0+(x1-x0)*.58),round(x0+(x1-x0)*.78)):
                r,g,b,a=tile.getpixel((x,y))
                if a>220 and r>g*1.12 and g>b*1.08 and r>65:
                    samples.append((r,g,b))
        assert samples, f'{p["name"]}: inspect skin sampling'
        samples.sort(key=lambda rgb: sum(rgb))
        skin_samples=samples[round(len(samples)*.55):max(round(len(samples)*.8),round(len(samples)*.55)+1)]
        skin='#'+''.join(f'{round(statistics.median(c)):02x}' for c in zip(*skin_samples))
        players[p['id']]={"name":p['name'],"src":src,"crop":[left+x0,top+y0,x1-x0,y1-y0],"cell":i,"skin":skin,"reference":p['reference'],"height":p['height'],"weight":p['weight']}
    print(f'PASS {src}: 34 visible heads and true transparency')
manifest={"kind":"Individually illustrated cartoon likenesses on a shared articulated skeleton","sourceRosterDate":queue['sourceRosterDate'],"generator":"Built-in image_gen; prompts and sources in tools/player-likenesses/","players":players}
(root/'public/assets/characters/likenesses/manifest.json').write_text(json.dumps(manifest,indent=4)+'\n')
(root/'public/scripts/player-likenesses.js').write_text('// Generated by tools/player-likenesses/build-manifest.py\nwindow.playerLikenesses = '+json.dumps(players,separators=(',',':'))+';\n')
print(f'{len(players)} player likenesses indexed by stable roster ID.')
